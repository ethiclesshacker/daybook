#!/usr/bin/env node
// @ts-check
// ======================================================
// Font Awesome, cut down to the icons this app draws.
//
//   node scripts/fa-subset.mjs          → rewrites src/icons.css
//   node scripts/fa-subset.mjs --check  → exits 1 if src/icons.css is stale
//
// `all.min.css` carried 2,000-odd icon rules, three font faces (solid,
// regular, brands) and the v4/v5 shims, for the ~110 solid icons used here.
// This keeps Font Awesome's base rules and utilities (fa-spin and friends)
// as they are, the solid face only, and an icon rule for every `fa-<name>`
// that appears anywhere under src/ — so a new icon in a template string is
// picked up by re-running this script. test/icons.test.js fails when an
// icon is used but missing from the subset.
// ======================================================

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const faDir = join(root, 'node_modules/@fortawesome/fontawesome-free');
export const SUBSET_PATH = join(root, 'src/icons.css');

// Names built at runtime (`fa-${cond ? 'a' : 'b'}`), which a scan cannot see.
const DYNAMIC = ['circle', 'circle-check'];
// Words that match `fa-…` in src/ without being icons: this script's own name
// in comments, and Font Awesome's utility classes.
export const NOT_ICONS = new Set(['subset', 'spin', 'fw', 'solid', 'brands', 'regular', 'classic', 'pulse', 'beat', 'xs', 'sm', 'lg', 'xl']);

/** Every `fa-<name>` written anywhere under src/, without the prefix. */
export function usedIconNames(dir = join(root, 'src')) {
  const names = new Set(DYNAMIC);
  const walk = d => {
    for (const entry of readdirSync(d)) {
      const path = join(d, entry);
      if (statSync(path).isDirectory()) walk(path);
      else if (/\.(js|html)$/.test(entry)) {
        for (const m of readFileSync(path, 'utf8').matchAll(/\bfa-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) names.add(m[1]);
      }
    }
  };
  walk(dir);
  return names;
}

/** The subset stylesheet, and which of `names` it found an icon for. */
export function buildSubset(names = usedIconNames()) {
  const css = readFileSync(join(faDir, 'css/fontawesome.css'), 'utf8');
  // Split into top-level blocks. Nested braces only occur in @keyframes and
  // @supports, which sit in the utility half and are kept whole.
  const blocks = [];
  let depth = 0, start = 0;
  for (let i = 0; i < css.length; i++) {
    if (css[i] === '{') depth++;
    else if (css[i] === '}' && --depth === 0) { blocks.push(css.slice(start, i + 1).trim()); start = i + 1; }
  }

  const kept = [];
  const found = new Set();
  for (const block of blocks) {
    const match = /^([^{]+)\{\s*--fa:\s*("[^"]*")\s*;?\s*\}$/s.exec(block);
    if (!match) { kept.push(block); continue; }       // base rule or utility
    const selectors = match[1].split(',').map(s => s.replace(/\/\*[\s\S]*?\*\//g, '').trim());
    const wanted = selectors.filter(s => names.has(s.replace(/^\.fa-/, '')));
    if (!wanted.length) continue;
    wanted.forEach(s => found.add(s.replace(/^\.fa-/, '')));
    kept.push(`${wanted.join(',\n')} {\n  --fa: ${match[2]};\n}`);
  }

  // The solid face only, pointing back into node_modules so Vite hashes it.
  const solid = readFileSync(join(faDir, 'css/solid.css'), 'utf8')
    .replace(/^\/\*![\s\S]*?\*\/\s*/, '')
    .replace('../webfonts/', '@fortawesome/fontawesome-free/webfonts/');

  const version = JSON.parse(readFileSync(join(faDir, 'package.json'), 'utf8')).version;
  const header = `/* GENERATED by scripts/fa-subset.mjs from @fortawesome/fontawesome-free ${version}; do not edit.
   Font Awesome Free by @fontawesome - https://fontawesome.com
   License - https://fontawesome.com/license/free (Icons: CC BY 4.0, Fonts: SIL OFL 1.1, Code: MIT License)
   Re-run \`node scripts/fa-subset.mjs\` after using a new icon. */\n`;
  return { css: header + kept.join('\n') + '\n' + solid, found };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { css } = buildSubset();
  if (process.argv.includes('--check')) {
    const current = readFileSync(SUBSET_PATH, 'utf8');
    if (current !== css) {
      console.error(`${relative(root, SUBSET_PATH)} is stale; run node scripts/fa-subset.mjs`);
      process.exit(1);
    }
    console.log('icons.css is current');
  } else {
    writeFileSync(SUBSET_PATH, css);
    console.log(`wrote ${relative(root, SUBSET_PATH)} (${css.length} bytes)`);
  }
}
